#!/usr/bin/env python3
"""
@docs ARCHITECTURE:Infrastructure:Execution

### AI Assist Note
**Tadpole OS Day-1 Bootstrapper (`tadpole_init`)**: Interactive and non-interactive
first-run configurator for brand-new operators. Generates cryptographically secure
tokens via `secrets.token_hex(32)` without echoing raw credentials, probes local
Ollama and Docker availability, detects hardware tier, and writes a hardened `.env`.

### 🔍 Debugging & Observability
- **Failure Path**: Unwritable workspace directory, malformed `.env`, or unreachable Ollama daemon.
- **Telemetry Link**: Search `[tadpole_init]` in console logs.
"""

import argparse
import json
import os
import platform
import secrets
import shutil
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional, Tuple

EMBEDDING_MODEL_MARKERS = ("embed", "minilm", "bge-", "e5-", "rerank")


def is_embedding_model(name: str) -> bool:
    """Return True if an Ollama tag represents an embedding/reranker model unsuitable for chat."""
    lower = name.lower()
    return any(marker in lower for marker in EMBEDDING_MODEL_MARKERS)


def select_chat_model(models: List[str], fallback: str) -> str:
    """Select the first chat-capable (non-embedding) Ollama model or fall back cleanly."""
    for model in models:
        if model and not is_embedding_model(model):
            return model
    return fallback


def is_docker_daemon_running(timeout: float = 3.0) -> bool:
    """Verify the Docker daemon is actually reachable (not merely installed on PATH)."""
    docker_bin = shutil.which("docker")
    if not docker_bin:
        return False
    try:
        res = subprocess.run(
            [docker_bin, "info"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=timeout,
            check=False,
        )
        return res.returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


DEFAULT_PRESETS: Dict[str, Dict[str, str]] = {
    "local": {
        "PRIVACY_MODE": "true",
        "OLLAMA_MODEL": "gemma4:e4b",
        "INFERENCE_CONCURRENCY": "2",
        "DEFAULT_AGENT_BUDGET_USD": "2.00",
    },
    "hybrid": {
        "PRIVACY_MODE": "false",
        "OLLAMA_MODEL": "gemma4:e4b",
        "INFERENCE_CONCURRENCY": "4",
        "DEFAULT_AGENT_BUDGET_USD": "5.00",
    },
    "cloud": {
        "PRIVACY_MODE": "false",
        "OLLAMA_MODEL": "gemma4:e4b",
        "INFERENCE_CONCURRENCY": "6",
        "DEFAULT_AGENT_BUDGET_USD": "10.00",
    },
}


def mask_token(token: str) -> str:
    """Mask sensitive tokens for safe terminal logging."""
    if len(token) <= 10:
        return "[REDACTED]"
    return f"{token[:4]}...{token[-4:]}"


def probe_ollama(host: str = "http://localhost:11434", timeout: float = 2.0) -> Tuple[bool, List[str]]:
    """Probe local Ollama HTTP API for installed models without failing hard."""
    url = f"{host.rstrip('/')}/api/tags"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "TadpoleOS/1.1.59"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            payload = json.loads(resp.read().decode("utf-8", errors="replace"))
            models = [m.get("name", "") for m in payload.get("models", []) if m.get("name")]
            return True, models
    except (urllib.error.URLError, TimeoutError, ValueError, OSError):
        return False, []


def detect_hardware_profile(probe_docker: bool = True) -> Dict[str, object]:
    """Collect lightweight cross-platform hardware and live sandbox daemon facts."""
    return {
        "os": platform.system(),
        "cpu_cores": os.cpu_count() or 1,
        "docker_available": is_docker_daemon_running() if probe_docker else False,
    }


def render_env_file(
    preset: str,
    neural_token: str,
    admin_token: Optional[str] = None,
    readonly_token: Optional[str] = None,
    ollama_host: str = "http://localhost:11434",
    ollama_model: Optional[str] = None,
    docker_sandbox: bool = False,
) -> str:
    """Build a hardened, commented .env configuration."""
    cfg = DEFAULT_PRESETS.get(preset, DEFAULT_PRESETS["hybrid"])
    selected_model = ollama_model or cfg["OLLAMA_MODEL"]
    lines = [
        "# Generated by execution/tadpole_init.py — Tadpole OS Day-1 Bootstrap",
        "# NEVER commit this file to version control.",
        "",
        "# Authentication (Primary Operator Token)",
        f"NEURAL_TOKEN={neural_token}",
    ]
    if admin_token:
        lines.append(f"NEURAL_TOKEN_ADMIN={admin_token}")
    if readonly_token:
        lines.append(f"NEURAL_TOKEN_READONLY={readonly_token}")

    lines.extend(
        [
            "ALLOWED_ORIGINS=http://localhost:3000,http://127.0.0.1:3000,http://localhost:5173,http://127.0.0.1:5173,tauri://localhost",
            "",
            "# Model & Runtime Profile",
            f"OLLAMA_HOST={ollama_host}",
            f"OLLAMA_MODEL={selected_model}",
            f"PRIVACY_MODE={cfg['PRIVACY_MODE']}",
            f"INFERENCE_CONCURRENCY={cfg['INFERENCE_CONCURRENCY']}",
            "",
            "# Safety & Governance Defaults",
            f"DEFAULT_AGENT_BUDGET_USD={cfg['DEFAULT_AGENT_BUDGET_USD']}",
            f"USE_SANDBOX_DOCKER={'true' if docker_sandbox else 'false'}",
            "ALLOW_HOST_SKILL_EXECUTION=false",
            "DATABASE_URL=sqlite:data/tadpole.db",
            "PORT=8000",
            "BIND_ADDRESS=127.0.0.1",
            "",
        ]
    )
    return "\n".join(lines)


def initialize_workspace(
    workspace: Path,
    preset: str = "hybrid",
    tiered_tokens: bool = False,
    force: bool = False,
    probe_local: bool = True,
) -> Dict[str, object]:
    """Generate a hardened .env file if absent (or when force=True)."""
    env_path = workspace / ".env"
    if env_path.exists() and not force:
        return {
            "status": "skipped",
            "reason": ".env already exists (pass --force to overwrite)",
            "env_path": str(env_path),
        }

    if preset not in DEFAULT_PRESETS:
        raise ValueError(f"Unsupported preset '{preset}'. Expected one of: {', '.join(DEFAULT_PRESETS)}")

    hw = detect_hardware_profile(probe_docker=probe_local)
    ollama_ok, ollama_models = probe_ollama() if probe_local else (False, [])
    selected_model = select_chat_model(ollama_models, DEFAULT_PRESETS[preset]["OLLAMA_MODEL"])

    neural_token = secrets.token_hex(32)
    admin_token = secrets.token_hex(32) if tiered_tokens else None
    readonly_token = secrets.token_hex(32) if tiered_tokens else None

    content = render_env_file(
        preset=preset,
        neural_token=neural_token,
        admin_token=admin_token,
        readonly_token=readonly_token,
        ollama_model=selected_model,
        docker_sandbox=bool(hw["docker_available"]),
    )
    if os.name != "nt":
        fd = os.open(str(env_path), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.chmod(env_path, 0o600)
    else:
        env_path.write_text(content, encoding="utf-8")

    (workspace / "data").mkdir(parents=True, exist_ok=True)
    (workspace / "logs").mkdir(parents=True, exist_ok=True)

    return {
        "status": "created",
        "preset": preset,
        "env_path": str(env_path),
        "token_preview": mask_token(neural_token),
        "admin_token_preview": mask_token(admin_token) if admin_token else None,
        "tiered_tokens": tiered_tokens,
        "ollama_detected": ollama_ok,
        "ollama_model": selected_model,
        "docker_sandbox": bool(hw["docker_available"]),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Tadpole OS Day-1 Operator Bootstrapper")
    parser.add_argument("--workspace", default=".", help="Target workspace root")
    parser.add_argument(
        "--preset",
        choices=["local", "hybrid", "cloud"],
        default=None,
        help="Model/safety tier preset (local | hybrid | cloud)",
    )
    parser.add_argument(
        "--tiered-tokens",
        action="store_true",
        help="Also generate dedicated NEURAL_TOKEN_ADMIN and NEURAL_TOKEN_READONLY tokens",
    )
    parser.add_argument("--non-interactive", action="store_true", help="Skip prompts and apply defaults")
    parser.add_argument("--force", action="store_true", help="Overwrite existing .env")
    args = parser.parse_args()

    workspace = Path(args.workspace).resolve()
    preset = args.preset or "hybrid"
    tiered = args.tiered_tokens

    if not args.non_interactive and args.preset is None and sys.stdin.isatty():
        print("[tadpole_init] Tadpole OS Day-1 Bootstrap")
        try:
            choice = input("Select preset [1=local, 2=hybrid (Recommended), 3=cloud] (default 2): ").strip()
            preset = {"1": "local", "2": "hybrid", "3": "cloud"}.get(choice, "hybrid")
            if not tiered:
                tier_ans = input("Generate dedicated Admin + ReadOnly RBAC tokens? [y/N]: ").strip().lower()
                tiered = tier_ans in {"y", "yes"}
        except (EOFError, KeyboardInterrupt):
            print("\n[tadpole_init] Input closed; applying default hybrid preset.")

    result = initialize_workspace(
        workspace=workspace,
        preset=preset,
        tiered_tokens=tiered,
        force=args.force,
        probe_local=True,
    )
    print(f"[tadpole_init] Result: {result['status']}")
    if result["status"] == "created":
        print(f"  Preset:         {result['preset']}")
        print(f"  NEURAL_TOKEN:   {result['token_preview']} (saved to .env)")
        if result.get("admin_token_preview"):
            print(f"  ADMIN_TOKEN:    {result['admin_token_preview']} (use NEURAL_TOKEN_ADMIN in UI for full Overlord controls)")
        print(f"  Ollama Ready:   {result['ollama_detected']} (model: {result['ollama_model']})")
        print(f"  Docker Sandbox: {result['docker_sandbox']}")
        print("  Next Step:      Run start_AA_tadpole.bat or `npm run engine` + `npm run dev`")
    else:
        print(f"  {result['reason']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

